#!/usr/bin/env python3
"""Helper for language-icons.sh: download Simple Icons SVGs, then embed the optimized ones in a Swift file."""
import json, pathlib, sys, urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
MAP = json.loads((ROOT / "scripts/language-icons.json").read_text())
OUT = ROOT / "Sources/GHCore/LanguageIconData.swift"


def download(raw_dir, tag):
    for slug in sorted(set(MAP.values())):
        url = f"https://raw.githubusercontent.com/simple-icons/simple-icons/{tag}/icons/{slug}.svg"
        with urllib.request.urlopen(url) as r:
            (pathlib.Path(raw_dir) / f"{slug}.svg").write_bytes(r.read())


def generate(raw_dir, min_dir, tag, svgo):
    raw_dir, min_dir = pathlib.Path(raw_dir), pathlib.Path(min_dir)
    slugs = sorted(set(MAP.values()))
    svgs = {}
    for slug in slugs:
        svg = (min_dir / f"{slug}.svg").read_text().strip()
        assert svg.startswith("<svg") and "viewBox" in svg and "xmlns" in svg, f"{slug}: unexpected SVG"
        assert '"#' not in svg, f"{slug}: cannot embed in a raw string"
        svgs[slug] = svg
    raw_total = sum((raw_dir / f"{s}.svg").stat().st_size for s in slugs)
    min_total = sum(len(v.encode()) for v in svgs.values())

    lines = [
        "// GENERATED by scripts/language-icons.sh. Do not edit by hand.",
        f"// Logos from Simple Icons {tag} (CC0-1.0, https://simpleicons.org), optimized with SVGO {svgo}.",
        "// The marks themselves remain trademarks of their owners; see THIRD_PARTY_NOTICES.md.",
        "",
        "enum LanguageIconData {",
        "    /// GitHub language name (lowercased) -> Simple Icons slug.",
        "    static let slugs: [String: String] = [",
    ]
    for lang, slug in sorted(MAP.items(), key=lambda kv: kv[0].lower()):
        lines.append(f'        "{lang.lower()}": "{slug}",')
    lines += ["    ]", "", "    /// Slug -> optimized SVG, all on a 24x24 viewBox.", "    static let svgs: [String: String] = ["]
    for slug in slugs:
        lines.append(f'        "{slug}": #"{svgs[slug]}"#,')
    lines += ["    ]", "}", ""]
    OUT.write_text("\n".join(lines))
    print(f"{len(slugs)} icons for {len(MAP)} languages: {raw_total} bytes raw -> {min_total} bytes optimized "
          f"({100 - 100 * min_total // raw_total}% smaller); wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    cmd, *args = sys.argv[1:]
    {"download": download, "generate": generate}[cmd](*args)
